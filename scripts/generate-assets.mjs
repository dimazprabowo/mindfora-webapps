// Generate all Mindfora brand assets from ONE source (the lotus mark below).
// Run: npm run assets   (re-run whenever the logo or brand colors change)
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import sharp from 'sharp';

const root = resolve(import.meta.dirname, '..');
const res = resolve(root, 'android/app/src/main/res');

// Lotus mark — identical to public/favicon.svg in the Laravel project (viewBox 32x32).
const LOTUS = [
    { d: 'M16 7c-2.5 3-4 5.5-4 8.5 0 2.2 1.8 4 4 4s4-1.8 4-4c0-3-1.5-5.5-4-8.5z', alpha: 0.95 },
    { d: 'M8 17c0-1.5.5-3 1.5-4.2 1.2 1 2 2.5 2 4.2 0 1.8-1.2 3.3-3 3.8-0.3-1.2-0.5-2.5-0.5-3.8z', alpha: 0.8 },
    { d: 'M24 17c0-1.5-.5-3-1.5-4.2-1.2 1-2 2.5-2 4.2 0 1.8 1.2 3.3 3 3.8.3-1.2.5-2.5.5-3.8z', alpha: 0.8 },
    { d: 'M16 20c-3 0-5.5 1.5-7 3.5 2 1.5 4.5 2.5 7 2.5s5-1 7-2.5c-1.5-2-4-3.5-7-3.5z', alpha: 0.9 },
];
// Brand colors — same tokens as tailwind.config.js (primary-400/600/700/950).
const COLOR = { light: '#34d399', base: '#059669', deep: '#047857', night: '#022c22' };

// Adaptive icon canvas is 108dp; the mark (16x19 units, centered at 16,16.5) is scaled to sit inside the 66dp safe zone.
const SCALE = 2.3;
const TX = 54 - 16 * SCALE;
const TY = 54 - 16.5 * SCALE;

const vectorPaths = (solid) =>
    LOTUS.map(
        ({ d, alpha }) =>
            `        <path android:fillColor="#FFFFFF" android:fillAlpha="${solid ? 1 : alpha}" android:pathData="${d}" />`,
    ).join('\n');

const vectorMark = (solid = false) => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-assets.mjs — do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${TX}" android:translateY="${TY}" android:scaleX="${SCALE}" android:scaleY="${SCALE}">
${vectorPaths(solid)}
    </group>
</vector>
`;

const vectorBackground = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-assets.mjs — do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear"
                android:startX="0" android:startY="0" android:endX="108" android:endY="108"
                android:startColor="${COLOR.light}" android:centerColor="${COLOR.base}" android:endColor="${COLOR.deep}" />
        </aapt:attr>
    </path>
</vector>
`;

const adaptiveIcon = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-assets.mjs — do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

// Pre-Android 12 splash (Android 12+ uses windowSplashScreen* attributes in styles.xml).
const splashDrawable = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/generate-assets.mjs — do not edit by hand. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item android:drawable="@drawable/ic_launcher_foreground" android:gravity="center" android:width="216dp" android:height="216dp" />
</layer-list>
`;

// Raster sources (legacy launcher icons, Play Store icon, offline-page logo).
const svgPaths = LOTUS.map(({ d, alpha }) => `<path d="${d}" fill="#fff" opacity="${alpha}"/>`).join('');
const gradient = `<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${COLOR.light}"/><stop offset=".5" stop-color="${COLOR.base}"/><stop offset="1" stop-color="${COLOR.deep}"/></linearGradient></defs>`;
const squareSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${gradient}<rect width="32" height="32" rx="7" fill="url(#g)"/>${svgPaths}</svg>`;
const roundSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${gradient}<circle cx="16" cy="16" r="16" fill="url(#g)"/>${svgPaths}</svg>`;
const fullBleedSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${gradient}<rect width="32" height="32" fill="url(#g)"/>${svgPaths}</svg>`;

const LEGACY_SIZES = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };

async function write(path, content) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
    console.log('  ✓', path.replace(root, '.'));
}

const png = (svg, size) => sharp(Buffer.from(svg), { density: 72 * (size / 32) }).resize(size, size).png().toBuffer();

await write(resolve(res, 'drawable/ic_launcher_foreground.xml'), vectorMark());
await write(resolve(res, 'drawable/ic_launcher_monochrome.xml'), vectorMark(true));
await write(resolve(res, 'drawable/ic_launcher_background.xml'), vectorBackground);
await write(resolve(res, 'drawable/splash.xml'), splashDrawable);
await write(resolve(res, 'mipmap-anydpi-v26/ic_launcher.xml'), adaptiveIcon);
await write(resolve(res, 'mipmap-anydpi-v26/ic_launcher_round.xml'), adaptiveIcon);

for (const [density, size] of Object.entries(LEGACY_SIZES)) {
    await write(resolve(res, `mipmap-${density}/ic_launcher.png`), await png(squareSvg, size));
    await write(resolve(res, `mipmap-${density}/ic_launcher_round.png`), await png(roundSvg, size));
}

// Play Store requires a full-bleed square 512x512 (Google applies the mask).
await write(resolve(root, 'assets/play-store-icon.png'), await png(fullBleedSvg, 512));
await write(resolve(root, 'src/logo.svg'), `${squareSvg}\n`);
